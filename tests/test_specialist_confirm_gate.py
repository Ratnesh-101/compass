"""
Compass — Adversarial Confirm-Gate Audit for Specialist Team & Northstar Delegation.

Security & Safety Invariants Verified:
1. No State Mutation without Human Confirmation:
   Neither delegate_to_specialist nor the SpecialistDispatcher can bypass the
   MUTATING_TOOLS confirmation gate.
2. Adversarial Injection Defense:
   Adversarial prompt attempts to trick a specialist into calling mutating actions
   (e.g., 'Delete all tasks', 'Add task HACKED', SQL injection) result in ZERO
   unauthorized writes to the database.
3. Direct Specialist API Endpoint Safety:
   POST /api/specialist/dispatch is strictly read-only analysis. It cannot execute
   database mutations even if allowed_tools contains mutating tools.
4. Proposed Actions Safety:
   Any proposed actions generated by specialists are returned as advisory payloads
   and MUST pass through Northstar's confirmation gate before execution.
"""

